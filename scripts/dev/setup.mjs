#!/usr/bin/env node
/**
 * Prepares a checkout to run locally with no account anywhere:
 *
 *   1. writes .dev.vars with random local secrets, unless the file already exists;
 *   2. applies the D1 migrations to the local database.
 *
 * Safe to run again. `npm run dev` and `npm run preview` run it first.
 */
import { spawnSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('../..', import.meta.url)));
const devVars = join(root, '.dev.vars');

if (!existsSync(devVars)) {
  const secret = () => randomBytes(32).toString('base64url');
  writeFileSync(
    devVars,
    [
      '# Local secrets, generated by scripts/dev/setup.mjs. Never committed.',
      `SESSION_SECRET=${secret()}`,
      `ADMIN_TOKEN=${secret()}`,
      '',
    ].join('\n'),
    { mode: 0o600 },
  );
  console.log('setup: wrote .dev.vars with local secrets');
}

const migrate = spawnSync(
  join(root, 'node_modules', '.bin', 'wrangler'),
  ['d1', 'migrations', 'apply', 'DB', '--local'],
  { cwd: root, encoding: 'utf8', env: { ...process.env, CI: '1' } },
);
if (migrate.status !== 0) {
  console.error(`${migrate.stdout ?? ''}${migrate.stderr ?? ''}`.trim());
  console.error('setup: applying the local D1 migrations failed');
  process.exit(1);
}
const summary = /No migrations to apply|✅|applied/i.test(migrate.stdout ?? '')
  ? 'local D1 migrations are applied'
  : 'local D1 migrations ran';
console.log(`setup: ${summary}`);
