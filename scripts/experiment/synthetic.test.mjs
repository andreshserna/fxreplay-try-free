import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'node:test';

import { generate, run, serialize } from './synthetic.mjs';

const SCRIPT = fileURLToPath(new URL('./synthetic.mjs', import.meta.url));
const FIXTURE = fileURLToPath(
  new URL('../../docs/experiments/fixtures/hero_signup.synthetic.json', import.meta.url),
);

test('the same seed gives byte-identical output, in process and as a command', () => {
  const first = run(['--seed', '7', '--per-arm', '6690']);
  const second = run(['--seed', '7', '--per-arm', '6690']);
  assert.equal(first.code, 0);
  assert.equal(first.stdout, second.stdout);

  const spawned = spawnSync(process.execPath, [SCRIPT, '--seed', '7', '--per-arm', '6690'], {
    encoding: 'utf8',
  });
  assert.equal(spawned.status, 0, spawned.stderr);
  assert.equal(spawned.stdout, first.stdout);
});

test('the committed fixture is exactly what seed 7 with 10500 per arm generates', () => {
  assert.equal(readFileSync(FIXTURE, 'utf8'), serialize(generate({ seed: 7, perArm: 10500 })));
});

test('a different seed gives different counts', () => {
  const seven = generate({ seed: 7, perArm: 10500 });
  const eight = generate({ seed: 8, perArm: 10500 });
  assert.notDeepEqual(seven.arms, eight.arms);
  assert.match(eight.note, /with seed 8\./);
});

test('counts are consistent in every arm, for several seeds and sizes', () => {
  for (const seed of [0, 1, 7, 42, 4294967295]) {
    for (const perArm of [1, 50, 6690]) {
      const { arms } = generate({ seed, perArm });
      const names = Object.keys(arms);
      assert.deepEqual(names, ['cta_button', 'inline_email'], 'the control is listed first');
      // Every visitor of the 2 × perArm lands in exactly one arm.
      assert.equal(arms.cta_button.exposed + arms.inline_email.exposed, 2 * perArm);
      for (const name of names) {
        const { exposed, signups, profiles, submitted, failed } = arms[name];
        const label = `seed ${seed}, ${perArm} per arm, ${name}`;
        for (const count of [exposed, signups, profiles, submitted, failed]) {
          assert.ok(Number.isInteger(count) && count >= 0, label);
        }
        assert.ok(signups <= exposed, `signups <= exposed: ${label}`);
        assert.ok(profiles <= signups, `profiles <= signups: ${label}`);
        assert.ok(submitted >= signups, `submitted >= signups: ${label}`);
        assert.ok(failed <= submitted, `failed <= submitted: ${label}`);
      }
    }
  }
});

test('the draws follow the assumed rates', () => {
  // With 100000 per arm the standard error of a 10% rate is √(0.1·0.9/100000) = 0.00095, so
  // 0.005 is more than five standard errors. The seed is fixed, so the check is deterministic;
  // the margins only keep it honest if the seed changes.
  const { arms } = generate({ seed: 1, perArm: 100000 });
  const rate = (arm, numerator, denominator) => arms[arm][numerator] / arms[arm][denominator];
  assert.ok(Math.abs(arms.cta_button.exposed / 200000 - 0.5) < 0.005, 'the split is 50/50');
  assert.ok(Math.abs(rate('cta_button', 'signups', 'exposed') - 0.1) < 0.005);
  assert.ok(Math.abs(rate('inline_email', 'signups', 'exposed') - 0.118) < 0.005);
  assert.ok(Math.abs(rate('cta_button', 'profiles', 'signups') - 0.46) < 0.02);
  assert.ok(Math.abs(rate('inline_email', 'profiles', 'signups') - 0.44) < 0.02);
  assert.ok(Math.abs(rate('cta_button', 'submitted', 'signups') - 1.15) < 0.02);
  assert.ok(Math.abs(rate('inline_email', 'failed', 'submitted') - 0.06) < 0.01);
});

test('the file says it is synthetic, first, and in its note', () => {
  const results = generate({ seed: 7, perArm: 10500 });
  assert.equal(Object.keys(results)[0], 'synthetic');
  assert.equal(results.synthetic, true);
  assert.equal(
    results.note,
    'Synthetic data generated by scripts/experiment/synthetic.mjs with seed 7. Not a measurement of anything.',
  );
  assert.equal(results.experiment, 'hero_signup');
  assert.deepEqual(results.generated_with.seed, 7);
  assert.deepEqual(results.period, { start: '2026-12-01', end: '2026-12-14', whole_weeks: 2 });
});

test('--out writes the same bytes as stdout and says it wrote synthetic data', () => {
  const dir = mkdtempSync(join(tmpdir(), 'synthetic-'));
  try {
    const out = join(dir, 'results.json');
    const written = run(['--seed', '3', '--per-arm', '100', '--out', out]);
    assert.equal(written.code, 0);
    assert.match(written.stdout, /^Wrote SYNTHETIC data to /);
    assert.equal(readFileSync(out, 'utf8'), run(['--seed', '3', '--per-arm', '100']).stdout);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('invalid usage is a one-line error and exit code 2', () => {
  const cases = [
    [['--per-arm', '6690'], /--seed is required/],
    [['--seed', '7'], /--per-arm is required/],
    [['--seed', '-1', '--per-arm', '10'], /--seed/],
    [['--seed', '1.5', '--per-arm', '10'], /--seed must be a non-negative integer/],
    [['--seed', '4294967296', '--per-arm', '10'], /--seed must be an integer from 0/],
    [['--seed', '7', '--per-arm', '0'], /--per-arm must be a positive integer/],
    [['--seed', '7', '--per-arm', '10', '--bogus'], /Unknown option '--bogus'/],
  ];
  for (const [argv, message] of cases) {
    const { code, stdout, stderr } = run(argv);
    assert.equal(code, 2, argv.join(' '));
    assert.equal(stdout, '');
    assert.match(stderr, /^synthetic: [^\n]+\n$/, `one line for ${argv.join(' ')}`);
    assert.match(stderr, message, argv.join(' '));
  }
});
