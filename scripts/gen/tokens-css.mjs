#!/usr/bin/env node
/**
 * Generates the token stylesheets from their JSON sources.
 *
 *   tokens/tokens.json      ->  tokens/tokens.css       the kit's tokens, as its README describes the file
 *   tokens/extensions.json  ->  tokens/extensions.css   what this project adds, kept apart
 *
 *   node scripts/gen/tokens-css.mjs           write both files
 *   node scripts/gen/tokens-css.mjs --check   fail if either file is out of date
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { REPO_ROOT, cssName, loadTokens } from '../lib/tokens.mjs';

const header = (source) =>
  `/* @generated by scripts/gen/tokens-css.mjs from ${source}. Do not edit: change the JSON and run \`npm run gen\`. */\n`;

function declaration(token) {
  if (!token.alias) return `  ${cssName(token.name)}: ${token.value};`;
  const target = `var(${cssName(token.alias)})`;
  const value =
    token.alpha === 1
      ? target
      : `color-mix(in srgb, ${target} ${Math.round(token.alpha * 100)}%, transparent)`;
  return `  ${cssName(token.name)}: ${value};`;
}

/** One :root block, with a comment line wherever the token group changes. */
function block(comment, tokens, { labelGroups = true } = {}) {
  const lines = [`/* ${comment} */`, ':root {'];
  let group;
  for (const token of tokens) {
    if (labelGroups && token.group !== group) {
      if (group !== undefined) lines.push('');
      lines.push(`  /* ${token.group} */`);
      group = token.group;
    }
    lines.push(declaration(token));
  }
  lines.push('}');
  return lines.join('\n');
}

export function renderKitCss(tokens) {
  const primitives = tokens.filter((token) => token.tier === 'primitive');
  const semantic = tokens.filter((token) => token.tier === 'semantic');
  return [
    header('tokens/tokens.json'),
    "/* FX Replay color tokens, rebuilt from the brand kit. Names are the kit's. */\n",
    block(
      `Primitives (${primitives.length}): the raw palette, and the only place literal color lives. Components never use these.`,
      primitives,
    ),
    '',
    block(
      `Semantic tokens (${semantic.length}): purpose-named aliases of the primitives. Build with these.`,
      semantic,
    ),
    '',
  ].join('\n');
}

export function renderExtensionsCss(tokens) {
  const extensions = tokens.filter((token) => token.tier === 'extension');
  return [
    header('tokens/extensions.json'),
    block(
      `Extensions (${extensions.length}): tokens this project adds to the kit. Each aliases a kit value. Reasons and contrast: docs/brand-notes.md.`,
      extensions,
      { labelGroups: false },
    ),
    '',
  ].join('\n');
}

export function render(root = REPO_ROOT) {
  const { tokens } = loadTokens(root);
  const files = { 'tokens/tokens.css': renderKitCss(tokens) };
  if (tokens.some((token) => token.tier === 'extension')) {
    files['tokens/extensions.css'] = renderExtensionsCss(tokens);
  }
  return files;
}

function main(argv) {
  const check = argv.includes('--check');
  let stale = 0;
  for (const [file, content] of Object.entries(render())) {
    const path = join(REPO_ROOT, file);
    const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (current === content) continue;
    if (check) {
      console.error(`tokens-css: ${file} is out of date. Run \`npm run gen\`.`);
      stale += 1;
    } else {
      writeFileSync(path, content);
      console.log(`tokens-css: wrote ${file}`);
    }
  }
  if (check && stale === 0) console.log('tokens-css: generated stylesheets are current.');
  return stale > 0 ? 1 : 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
