#!/usr/bin/env node
/**
 * Contrast check.
 *
 * Computes the WCAG contrast ratio of every pair in tokens/contrast-pairs.json
 * from the token sources, and fails when a pair the interface uses is below its
 * threshold: 4.5:1 for text, 3:1 for large text and for the boundaries of controls.
 *
 *   node scripts/checks/contrast.mjs               check the `ui` pairs
 *   node scripts/checks/contrast.mjs --write-docs  also rewrite the tables in docs/brand-notes.md
 *   node scripts/checks/contrast.mjs --check-docs  also fail if those tables are out of date
 *
 * Ratios are compared unrounded and displayed truncated to two decimals, so a
 * displayed value never overstates the real one.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { contrastRatio } from '../lib/color.mjs';
import { REPO_ROOT, loadTokens, paintedColor, resolveToken } from '../lib/tokens.mjs';

export const PAIRS_FILE = 'tokens/contrast-pairs.json';
export const DOCS_FILE = 'docs/brand-notes.md';
export const THRESHOLDS = { text: 4.5, 'large-text': 3, boundary: 3 };

const KIND_LABEL = { text: 'text', 'large-text': 'large text', boundary: 'boundary' };
const MARKER = { start: '<!-- contrast:start -->', end: '<!-- contrast:end -->' };

export const formatRatio = (ratio) => (Math.floor(ratio * 100) / 100).toFixed(2);

/** Measures one pair. Throws on an unknown token or kind. */
export function measure(byName, pair) {
  const threshold = THRESHOLDS[pair.kind];
  if (threshold === undefined) throw new Error(`Unknown kind "${pair.kind}" for ${pair.foreground} on ${pair.background}`);
  const background = paintedColor(byName, pair.background, pair.over);
  const foreground = paintedColor(byName, pair.foreground, pair.background);
  const ratio = contrastRatio(foreground, background);
  return {
    ...pair,
    foregroundHex: resolveToken(byName, pair.foreground).hex,
    backgroundHex: resolveToken(byName, pair.background).hex,
    ratio,
    threshold,
    passes: ratio >= threshold,
  };
}

/** Measures every pair. `problems` lists what must stop the build. */
export function audit(root = REPO_ROOT) {
  const { byName } = loadTokens(root);
  const pairs = JSON.parse(readFileSync(join(root, PAIRS_FILE), 'utf8'));
  const problems = [];

  const ui = pairs.ui.map((pair) => {
    for (const name of [pair.foreground, pair.background]) {
      if (byName.get(name)?.tier === 'primitive') {
        problems.push(`${name} is a primitive. A pair the interface uses names semantic or extension tokens only.`);
      }
    }
    const result = measure(byName, pair);
    if (!result.passes) {
      problems.push(`${pair.foreground} on ${pair.background} is ${formatRatio(result.ratio)}:1 and needs ${result.threshold}:1 (${pair.use}).`);
    }
    return result;
  });
  const kit = pairs.kit.map((pair) => measure(byName, pair));
  return { ui, kit, problems };
}

const row = (cells) => `| ${cells.join(' | ')} |`;
const pairCell = (result) => `\`${result.foreground}\` on \`${result.background}\``;
const hexCell = (result) => `${result.foregroundHex} on ${result.backgroundHex}`;
const needsCell = (result) => `${result.threshold} (${KIND_LABEL[result.kind]})`;

export function renderDocs({ ui, kit }) {
  return [
    MARKER.start,
    '<!-- Generated by scripts/checks/contrast.mjs from tokens/contrast-pairs.json. Do not edit: run `npm run gen`. -->',
    '',
    `**Pairs the interface uses (${ui.length}).** Enforced: the build fails if one drops below its threshold.`,
    '',
    row(['Pair', 'Values', 'Ratio', 'Needs', 'Use']),
    row(['---', '---', '---', '---', '---']),
    ...ui.map((result) => row([pairCell(result), hexCell(result), `${formatRatio(result.ratio)}:1`, needsCell(result), result.use])),
    '',
    `**The kit's own pairings (${kit.length}).** An audit, not a gate.`,
    '',
    row(['Pair', 'Values', 'Ratio', 'Needs', 'Result', 'What it means for us']),
    row(['---', '---', '---', '---', '---', '---']),
    ...kit.map((result) => row([pairCell(result), hexCell(result), `${formatRatio(result.ratio)}:1`, needsCell(result), result.passes ? 'pass' : '**fail**', result.note])),
    '',
    'Ratios use the WCAG 2 formula. They are compared unrounded and shown truncated to two decimals.',
    MARKER.end,
  ].join('\n');
}

/** Returns the document with its generated section replaced, or null if the markers are missing. */
export function replaceSection(document, section) {
  const start = document.indexOf(MARKER.start);
  const end = document.indexOf(MARKER.end);
  if (start === -1 || end === -1 || end < start) return null;
  return document.slice(0, start) + section + document.slice(end + MARKER.end.length);
}

function main(argv) {
  const results = audit();
  for (const result of results.ui) {
    console.log(`${result.passes ? 'pass' : 'FAIL'}  ${formatRatio(result.ratio).padStart(5)}:1  needs ${String(result.threshold).padEnd(3)}  ${result.foreground} on ${result.background}`);
  }
  let failed = results.problems.length > 0;
  for (const problem of results.problems) console.error(`contrast: ${problem}`);

  if (argv.includes('--write-docs') || argv.includes('--check-docs')) {
    const path = join(REPO_ROOT, DOCS_FILE);
    const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
    const updated = replaceSection(current, renderDocs(results));
    if (updated === null) {
      console.error(`contrast: ${DOCS_FILE} has no ${MARKER.start} ... ${MARKER.end} section.`);
      failed = true;
    } else if (updated !== current) {
      if (argv.includes('--write-docs')) {
        writeFileSync(path, updated);
        console.log(`contrast: updated the tables in ${DOCS_FILE}`);
      } else {
        console.error(`contrast: the tables in ${DOCS_FILE} are out of date. Run \`npm run gen\`.`);
        failed = true;
      }
    }
  }

  if (!failed) console.log(`contrast: OK, ${results.ui.length} interface pair(s) pass.`);
  return failed ? 1 : 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (error) {
    console.error(`contrast: ${error.message}`);
    process.exitCode = 2;
  }
}
